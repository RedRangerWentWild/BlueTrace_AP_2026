#!/usr/bin/env python3
"""Load BlueTrace's own data into the schema of dbms/03_schema.sql.

    python3 dbms/load_app_data.py | psql -d bluetrace -v ON_ERROR_STOP=1

Writes SQL to stdout. Standard library only (plus dbms/bluetrace_logic.py). Everything is read from the app
itself, nothing is retyped:

  blue-grid/index.html                 CITIES, RULESETS, OUTCOME, CODE_CHUNK and the
                                       (outcome, code) pairs inside decide()
  blue-grid/data/corpus.json           chunks, tags, intents, parameters
  blue-grid/data/<city>/stats.json     city statistics
  blue-grid/data/<city>/flagged_buildings.geojson

The screening / certificate rows at the end are ILLUSTRATIVE: the app keeps a
plot check only in the browser, so there is no history to export. The nine
example plots below were chosen so that every one of the 11 reason codes
occurs at least once; their measurements are examples, not raster readings.
Their reasons, verdicts and certificate digests are not typed in: they are
computed by decide_() and fnv1a() in dbms/bluetrace_logic.py, which mirror
decide() and fnv1a() in index.html line for line.
"""
import json
import sys

from bluetrace_logic import (APP, CITIES, CODE_CHUNK, CODE_OUTCOME, CORPUS, OUTCOME_RANK, OUTCOME_TITLE,
                             RULESETS, canonical, cert_ref, decide_)

out = sys.stdout
def emit(s=''):
    out.write(s + '\n')

def lit(v):
    """SQL literal."""
    if v is None:
        return 'NULL'
    if isinstance(v, bool):
        return 'TRUE' if v else 'FALSE'
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"

AUTH_EXTERNAL = {'statute', 'court', 'agency-survey', 'dataset-doc'}   # check_corpus.py, EXTERNAL
AUTHORITIES = ['statute', 'court', 'agency-survey', 'dataset-doc', 'repo-derived', 'editorial']

emit('-- generated by dbms/load_app_data.py from the BlueTrace app files')
emit('SET search_path TO bluetrace;')
emit('BEGIN;')
emit()
emit('-- AUTHORITY (check_corpus.py: EXTERNAL authorities must carry a url)')
emit('INSERT INTO authority (authority, url_required) VALUES')
emit(',\n'.join('  (%s, %s)' % (lit(a), lit(a in AUTH_EXTERNAL)) for a in AUTHORITIES) + ';')
emit()
emit('-- OUTCOME (index.html, OUTCOME; ranks from decide())')
emit('INSERT INTO outcome (outcome, title, rank) VALUES')
emit(',\n'.join('  (%s, %s, %d)' % (lit(k), lit(OUTCOME_TITLE[k]), OUTCOME_RANK[k]) for k in OUTCOME_RANK) + ';')
emit()
emit('-- BUFFER_RULE (index.html, RULESETS)')
emit('INSERT INTO buffer_rule (rule_id, rule_label, lake_m, drain_m) VALUES')
emit(',\n'.join('  (%s, %s, %d, %d)' % (lit(r['id']), lit(r['label']), r['lakeM'], r['drainM'])
                for r in RULESETS.values()) + ';')
emit()
emit('-- CITY (index.html, CITIES + data/<city>/stats.json) and HOTSPOT')
for key, c in CITIES.items():
    sp = APP / 'data' / key / 'stats.json'
    st = json.loads(sp.read_text()) if sp.exists() else {}
    b = c['bounds']
    emit('INSERT INTO city VALUES (%s);' % ', '.join(lit(v) for v in (
        key, c['label'], c['sub'], b[0], b[1], b[2], b[3], c['zones'],
        st.get('historic_ha'), st.get('present_ha'), st.get('lost_ha'), st.get('encroached_ha'),
        st.get('floodprone_ha'), st.get('buildings_in_floodprone'))))
    for h in c['hotspots']:
        emit('INSERT INTO hotspot VALUES (%s, %s, %s, %s, %d);' % (lit(key), lit(h['name']), h['lon'], h['lat'], h['px']))
emit()

# ---------------------------------------------------------------- corpus
emit('-- CHUNK, CHUNK_TAG, CHUNK_INTENT (data/corpus.json, version %s)' % CORPUS['corpus_version'])
for c in CORPUS['chunks']:
    emit('INSERT INTO chunk VALUES (%s);' % ', '.join(lit(v) for v in (
        c['id'], c['title'], c['kind'], c['authority'], c['source'], c['url'] or None, c['body'])))
for c in CORPUS['chunks']:
    for t in sorted(set(c['tags'])):
        emit('INSERT INTO chunk_tag VALUES (%s, %s);' % (lit(c['id']), lit(t)))
    for i in sorted(set(c['intents'])):
        emit('INSERT INTO chunk_intent VALUES (%s, %s);' % (lit(c['id']), lit(i)))
emit()
emit('-- PARAM (data/corpus.json "params": name -> chunk, value, unit)')
for name, p in sorted(CORPUS['params'].items()):
    emit('INSERT INTO param VALUES (%s, %s, %s, %s, %s);' % (lit(name), lit(p['chunk']), repr(p['v']),
                                                           lit(p.get('pm')), lit(p.get('u'))))
emit()
emit('-- REASON_CODE (decide() for the outcome, CODE_CHUNK for the cited chunk)')
emit('INSERT INTO reason_code (reason_code, outcome, chunk_id) VALUES')
emit(',\n'.join('  (%s, %s, %s)' % (lit(k), lit(CODE_OUTCOME[k]), lit(CODE_CHUNK[k])) for k in sorted(CODE_CHUNK)) + ';')
emit()

# ---------------------------------------------------------------- buildings
for key in CITIES:
    gp = APP / 'data' / key / 'flagged_buildings.geojson'
    if not gp.exists():
        continue
    feats = json.loads(gp.read_text())['features']
    emit('-- BUILDING: %d flagged footprints from data/%s/flagged_buildings.geojson' % (len(feats), key))
    for k in range(0, len(feats), 500):
        rows = []
        for f in feats[k:k + 500]:
            p = f['properties']
            rows.append('  (%s)' % ', '.join(lit(v) for v in (
                key, json.dumps(f['geometry'], separators=(',', ':')), p['verdict'], p['risk_score'],
                p['lost_frac'], p['flow_frac'], p['upstream_km2'], p['hand_m'], p['area_in_meters'],
                p['confidence'])))
        emit('INSERT INTO building (city_key, geometry, verdict, risk_score, lost_frac, flow_frac,\n'
             '                      upstream_km2, hand_m, area_m2, confidence) VALUES')
        emit(',\n'.join(rows) + ';')
emit()

# ---------------------------------------------------------------- example screenings
D8 = {'E': (1, 0), 'SE': (1, 1), 'S': (0, 1), 'SW': (-1, 1), 'W': (-1, 0), 'NW': (-1, -1), 'N': (0, -1), 'NE': (1, -1)}
MERIT = 1 / 1200
import math
def step_length(lat, direction):
    """metresBetween() for one MERIT cell step: the length traceDownstream() adds."""
    dx, dy = D8[direction]
    ex = dx * MERIT * 111320 * math.cos(math.radians(lat))
    ny = dy * MERIT * 110574
    return round(math.hypot(ex, ny), 1)

