emit('-- SCREENING, SCREENING_REASON, ROUTE_STEP, CERTIFICATE, CERTIFICATE_CHUNK')
emit('-- Illustrative plot checks (see the module docstring). Reasons and verdicts are')
emit('-- computed by decide_(), a line-for-line port of decide(); digests by fnv1a().')
seq = 0
for n, (lat, lon, plot_m, rule_id, m, upa, steps, ended, cert) in enumerate(EXAMPLES, start=1):
    rule = RULESETS[rule_id]
    verdict, reasons = decide_(m, rule)
    # plot checks 20 minutes apart from 10:00 IST; a certificate is issued 3 minutes after its check
    checked = '2026-11-12 %02d:%02d:00+05:30' % (10 + (n - 1) * 20 // 60, (n - 1) * 20 % 60)
    emit('-- example %d: %s (%s)' % (n, verdict, ', '.join(c for c, _ in reasons)))
    emit('INSERT INTO screening (checked_at, city_key, rule_id, lat, lon, plot_m, dist_present, dist_historic,'
         ' dist_drain, last_water_year, occurrence, hand_m, encroached, upa_km2, storage_lpm2, route_ended_by)'
         ' VALUES')
    emit('  (%s);' % ', '.join(lit(v) for v in (
        checked, 'bengaluru', rule_id, lat, lon, plot_m, m['distPresent'], m['distHistoric'], m['distDrain'],
        m['lastWaterYear'], m['occurrence'], m['handM'], m['encroached'], upa,
        30 if n % 2 else None, ended)))
    for code, text in reasons:
        emit('INSERT INTO screening_reason VALUES (currval(pg_get_serial_sequence(\'screening\', \'screening_id\')), %s, %s);'
             % (lit(code), lit(text)))
    for k, (d, s_upa, s_hand) in enumerate(steps, start=1):
        emit('INSERT INTO route_step VALUES (currval(pg_get_serial_sequence(\'screening\', \'screening_id\')), %d, %s, %s, %s, %s);'
             % (k, lit(d), step_length(lat, d), s_upa, s_hand))
    if cert:
        _, generator, chunks = cert
        import datetime
        t = datetime.datetime.fromisoformat(checked) + datetime.timedelta(minutes=3, seconds=n * 7, milliseconds=n * 113)
        iso = t.astimezone(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%S.') + '%03dZ' % (t.microsecond // 1000)
        seq += 1
        canon = canonical('bengaluru', lat, lon, plot_m, rule, m, verdict, iso,
                          CORPUS['corpus_version'], generator, chunks)
        ref = cert_ref(iso, seq, canon)
        emit('INSERT INTO certificate (cert_ref, screening_id, issued_at, corpus_version, generator) VALUES'
             " (%s, currval(pg_get_serial_sequence('screening', 'screening_id')), %s, %s, %s);"
             % (lit(ref), lit(iso), lit(CORPUS['corpus_version']), lit(generator)))
        for k, c in enumerate(chunks, start=1):
            emit('INSERT INTO certificate_chunk VALUES (%s, %s, %d);' % (lit(ref), lit(c), k))
emit("SELECT setval('certificate_seq', %d);" % seq)
emit()
emit('COMMIT;')
emit('ANALYZE;')
